// The sample: two real domains' email DNS on 20 Nov 2026 (both belong to this series' author), read through
// dns.google. Writes the frozen answers for the app and the templates' sample values.
// Run: node --experimental-strip-types scripts/sample.ts
import { writeFileSync } from "node:fs";
import { analyse, gather, toValues, type Resolve } from "../templates/_shared/mail.ts";

const DATE = "2026-11-20";
const DOMAINS = ["getrevlio.com", "provryn.pro"];
const resolve: Resolve = async (name, type) => {
  const j = await fetch(`https://dns.google/resolve?name=${encodeURIComponent(name)}&type=${type}`).then((r) => r.json());
  return (j.Answer ?? []).filter((a: { type: number }) => a.type === (type === "MX" ? 15 : 16)).map((a: { data: string }) => a.data);
};
const answers = Object.fromEntries(await Promise.all(DOMAINS.map(async (d) => [d, await gather(d, resolve)] as const)));
writeFileSync(new URL(`../public/samples/domains-${DATE}.json`, import.meta.url), JSON.stringify({ read: DATE, resolver: "dns.google", answers }, null, 2) + "\n");
const values = toValues(analyse(DOMAINS[0], answers[DOMAINS[0]]), { checked: DATE, preparedBy: "Kestrel Web Studio", client: "Revlio" });
const json = JSON.stringify(values, null, 2);
writeFileSync(new URL("../docs/getrevlio.json", import.meta.url), `${json}\n`);
writeFileSync(
  new URL("../templates/_shared/example.ts", import.meta.url),
  `// The sample: getrevlio.com's real email DNS on ${DATE} (the series author's own domain), read through dns.google.\n// Generated by scripts/sample.ts. "Kestrel Web Studio" (who prepared it) is made up.\nconst example = ${json};\n\nexport default example;\n`,
);
console.log(DOMAINS.map((d) => `${d}: ${analyse(d, answers[d]).verdict}`).join(", "));
